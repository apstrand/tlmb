// `build.rs` includes this file rather than importing it, because a build
// script cannot depend on the crate it builds. That rules out inner doc
// comments here: included mid-file, they would not be at the top of anything.

/// The commands the window's page may call.
///
/// One list, because three places have to agree about it: `build.rs` declares
/// the names to Tauri so a capability is allowed to name them, the capability
/// in [`crate::run`]'s setup grants them to this process's loopback server, and
/// `mailbox.js` calls them. A name left out of the capability is not a quiet
/// no-op — it is `Command … not allowed by ACL` where the reader expected a
/// button to work.
pub const COMMANDS: [&str; 4] = [
    "update_status",
    "update_check",
    "update_install",
    "update_restart",
];

/// The ACL permission that allows `command`.
///
/// Tauri generates one `allow-<command>` permission per declared command, in
/// kebab-case (see `permissions/autogenerated/`).
// `build.rs` includes this file for `COMMANDS` alone, where this is dead.
#[allow(dead_code)]
pub fn allow(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

#[cfg(test)]
mod tests {
    /// The grant has to name the permission Tauri actually generated. It is
    /// spelled differently from the command, and getting it wrong costs
    /// nothing at build time and everything at the click: `update_check` was
    /// declared, handled and called for four releases while the capability
    /// granted the other three, so the About pane's button answered
    /// `Command update_check not allowed by ACL`.
    #[test]
    fn every_command_is_granted_by_the_name_tauri_generated_for_it() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions")
            .join("autogenerated");
        for command in super::COMMANDS {
            let path = dir.join(format!("{command}.toml"));
            let toml = std::fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("{} is not there: {e}", path.display()));
            let identifier = super::allow(command);
            assert!(
                toml.contains(&format!("identifier = \"{identifier}\"")),
                "{command} has no {identifier} permission in {}",
                path.display()
            );
        }
    }
}
